// v01ChartCases are the values the chart upgrade from 0.1.0 is checked with:
// the default (mode kubernetes, two replicas: the HA install), standalone,
// the edge Deployment, hostNetwork and DHCP. Each renders with the chart of
// 0.1.0 and with this one.
var v01ChartCases = []struct{ name, values string }{
	{"default", ""},
	{"standalone", "mode: standalone"},
	{"edge", "edge: {enabled: true}"},
	{"hostnetwork", "hostNetwork: {enabled: true}"},
	{"dhcp", "dhcp: {enabled: true, serverAddress: 192.0.2.67}"},
}

// v01ChartDir holds what the 0.1.0 chart renders for v01ChartCases, reduced
// to the fields Kubernetes or Helm do not let an upgrade change.
const v01ChartDir = "testdata/v0.1.0/chart"

// immutable reduces a rendered chart to the fields that `helm upgrade`
// cannot change in place, keyed "<kind>/<name>": every object (a name that
// disappears is an object Helm deletes), workload selectors and the
// StatefulSet's serviceName, podManagementPolicy and volumeClaimTemplates,
// a Service's clusterIP, a Secret's type, data keys and resource policy
// (generated values are looked up by key and must survive the upgrade), and
// the roleRef of every binding.
func immutable(t *testing.T, rendered []byte) map[string]map[string]any {
	t.Helper()
	out := map[string]map[string]any{}
	for _, doc := range decodeDocs(t, rendered) {
		kind, name := str(doc["kind"]), str(dig(doc, "metadata", "name"))
		fields := map[string]any{"namespace": dig(doc, "metadata", "namespace")}
		switch kind {
		case "Deployment", "DaemonSet":
			fields["selector"] = dig(doc, "spec", "selector")
		case "StatefulSet":
			fields["selector"] = dig(doc, "spec", "selector")
			fields["serviceName"] = dig(doc, "spec", "serviceName")
			fields["podManagementPolicy"] = dig(doc, "spec", "podManagementPolicy")
			var claims []any
			for _, c := range list(dig(doc, "spec", "volumeClaimTemplates")) {
				claims = append(claims, map[string]any{"name": dig(c, "metadata", "name"), "spec": dig(c, "spec")})
			}
			fields["volumeClaimTemplates"] = claims
		case "Service":
			fields["clusterIP"] = dig(doc, "spec", "clusterIP")
		case "Secret":
			var keys []string
			for _, section := range []string{"data", "stringData"} {
				for k := range mapOf(doc[section]) {
					keys = append(keys, k)
				}
			}
			sort.Strings(keys)
			fields["type"] = doc["type"]
			fields["keys"] = keys
			fields["resourcePolicy"] = dig(doc, "metadata", "annotations", "helm.sh/resource-policy")
		case "RoleBinding", "ClusterRoleBinding":
			fields["roleRef"] = doc["roleRef"]
		case "PersistentVolumeClaim":
			fields["spec"] = doc["spec"]
		}
		out[kind+"/"+name] = fields
	}
	return out
}

// updateV01Chart regenerates testdata/v0.1.0/chart from the v0.1.0 tag. It
// is a flag of its own, not -update: the fixture describes a release that
// does not change, so `make deploy-assets` (-update) only compares it, and
// neither that step nor any other test needs the tag (a CI checkout has no
// tags). Regenerating it is needed only when immutable() changes.
var updateV01Chart = flag.Bool("update-v01-chart", false, "rewrite testdata/v0.1.0/chart from the v0.1.0 tag")

// v01ChartRegen is the command that regenerates testdata/v0.1.0/chart.
const v01ChartRegen = "go test ./deploy -run TestChartUpgradeFromV01 -update-v01-chart"

// TestChartUpgradeFromV01 renders the chart of this release with the values
// of v01ChartCases and compares it with what the chart of 0.1.0 rendered
// (testdata/v0.1.0/chart, regenerated from the v0.1.0 tag with
// -update-v01-chart):
// every object of 0.1.0 is still rendered, under the same name, with the
// same immutable fields. A change here makes `helm upgrade` from 0.1.0 fail
// (a selector, a claim template, a Secret type, a roleRef) or delete an
// object an installation relies on (a Service address, a generated key).
// Objects new in this release are allowed.
func TestChartUpgradeFromV01(t *testing.T) {
	helm := helmBin(t)
	var oldChart string
	if *updateV01Chart {
		oldChart = v01Chart(t)
	}
	for _, tc := range v01ChartCases {
		t.Run(tc.name, func(t *testing.T) {
			golden := filepath.Join(v01ChartDir, tc.name+".yaml")
			if *updateV01Chart {
				out, err := renderChartAt(t, helm, oldChart, tc.values)
				if err != nil {
					t.Fatalf("helm template of the 0.1.0 chart: %v", err)
				}
				b, err := yaml.Marshal(immutable(t, out))
				if err != nil {
					t.Fatal(err)
				}
				values := tc.values
				if values == "" {
					values = "(the chart defaults)"
				}
				header := "# Immutable fields of the 0.1.0 chart (deploy/helm/kudurru at the v0.1.0 tag)\n# rendered with values: " + values + "\n# Generated by: " + v01ChartRegen + "\n"
				if err := os.MkdirAll(filepath.Dir(golden), 0o750); err != nil {
					t.Fatal(err)
				}
				if err := os.WriteFile(golden, append([]byte(header), b...), 0o644); err != nil { //nolint:gosec // committed repository file
					t.Fatal(err)
				}
			}
			b, err := os.ReadFile(golden) //nolint:gosec // committed fixture
			if err != nil {
				t.Fatalf("%v (regenerate with %s)", err, v01ChartRegen)
			}
			var was map[string]map[string]any
			if err := yaml.Unmarshal(b, &was); err != nil {
				t.Fatal(err)
			}
			if len(was) == 0 {
				t.Fatal("empty 0.1.0 fixture")
			}
			out, err := renderChart(t, tc.values)
			if err != nil {
				t.Fatalf("helm template: %v", err)
			}
			// Through YAML, so that both sides have the same types.
			cur, err := yaml.Marshal(immutable(t, out))
			if err != nil {
				t.Fatal(err)
			}
			var now map[string]map[string]any
			if err := yaml.Unmarshal(cur, &now); err != nil {
				t.Fatal(err)
			}
			for key, fields := range was {
				got, ok := now[key]
				if !ok {
					t.Errorf("%s of the 0.1.0 chart is no longer rendered: helm upgrade deletes it", key)
					continue
				}
				if !reflect.DeepEqual(got, fields) {
					t.Errorf("%s changed a field an upgrade cannot change\n 0.1.0: %v\n  now: %v", key, fields, got)
				}
			}
		})
	}
}

// renderChartAt runs helm template for the chart in dir.
func renderChartAt(t *testing.T, helm, dir, values string) ([]byte, error) {
	t.Helper()
	f := filepath.Join(t.TempDir(), "values.yaml")
	if err := os.WriteFile(f, []byte(values), 0o600); err != nil {
		t.Fatal(err)
	}
	cmd := exec.Command(helm, "template", "kudurru", dir, "--namespace", releaseNS, "--values", f) //nolint:gosec // fixed binary, test arguments
	var stderr bytes.Buffer
	cmd.Stderr = &stderr
	out, err := cmd.Output()
	if err != nil {
		return nil, errors.New(err.Error() + ": " + stderr.String())
	}
	return out, nil
}

// v01Chart unpacks deploy/helm/kudurru of the v0.1.0 tag into a temporary
// directory and returns the chart directory.
func v01Chart(t *testing.T) string {
	t.Helper()
	cmd := exec.Command("git", "archive", "--format=tar", "v0.1.0", "deploy/helm/kudurru") //nolint:gosec // fixed arguments
	cmd.Dir = repoRoot(t)
	out, err := cmd.Output()
	if err != nil {
		t.Fatalf("git archive v0.1.0: %v (-update-v01-chart needs the tag: git fetch origin tag v0.1.0)", err)
	}
	dir := t.TempDir()
	tr := tar.NewReader(bytes.NewReader(out))
	for {
		h, err := tr.Next()
		if errors.Is(err, io.EOF) {
			break
		}
		if err != nil {
			t.Fatal(err)
		}
		if h.Typeflag != tar.TypeReg {
			continue
		}
		if !filepath.IsLocal(h.Name) {
			t.Fatalf("archive entry %q", h.Name)
		}
		path := filepath.Join(dir, h.Name) //nolint:gosec // G305: IsLocal above
		if err := os.MkdirAll(filepath.Dir(path), 0o750); err != nil {
			t.Fatal(err)
		}
		b, err := io.ReadAll(tr)
		if err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, b, 0o600); err != nil {
			t.Fatal(err)
		}
	}
	return filepath.Join(dir, "deploy", "helm", "kudurru")
}
