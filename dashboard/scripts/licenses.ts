/** Packages that ship no licence file (Astryx 0.6.x): the declared licence's text. */
function fallback(pkg: Pkg, lic: string): string {
  const author = typeof pkg.author === 'string' ? pkg.author : (pkg.author?.name ?? '');
  const holder = pkg.name.startsWith('@astryxdesign/') ? 'Meta Platforms, Inc. and affiliates' : author || pkg.name;
  if (lic === 'MIT') return `MIT License\n\nCopyright (c) ${holder}\n\n${MIT}`;
  return `(no licence file shipped; package.json declares ${lic}; see ${pkg.homepage ?? 'the package'})`;
}

const out: string[] = [
  'Third-party software in the kudurru dashboard bundle',
  '=====================================================',
  '',
  'Generated by dashboard/scripts/licenses.ts from the production dependencies.',
  '',
];
const bad: string[] = [];
for (const [name, { pkg, dir }] of [...seen].sort(([a], [b]) => a.localeCompare(b))) {
  const lic = pkg.license ?? 'UNKNOWN';
  if (DENY.test(lic)) bad.push(`${name}@${pkg.version} (${lic})`);
  out.push(`${name} ${pkg.version} (${lic})`, '-'.repeat(60));
  const notice = textOf(dir, /^NOTICE(\.(md|txt))?$/i);
  if (notice) out.push(notice, '');
  out.push(textOf(dir, /^(LICEN[CS]E|COPYING)(\.(md|txt))?$/i) || fallback(pkg, lic), '', '');
}

// Assets the dashboard shows that the Go binary serves rather than the
// bundle: the catalogue logos (GET /api/v1/catalogue/icons/{slug}.svg).
const assets: { name: string; license: string; text: string; note: string }[] = [
  {
    name: 'Dashboard Icons (https://github.com/homarr-labs/dashboard-icons), commit 104a791794ef',
    license: 'Apache-2.0',
    text: '../internal/listdata/catalogue/icons/LICENSE',
    note:
      'Service, search-engine and DNS-provider logos served by the kudurru API from internal/listdata/catalogue/icons ' +
      '(files and checksums in PROVENANCE.md there). The logos are trademarks of their respective owners, ' +
      'shown only to identify what they name.',
  },
];
for (const a of assets) {
  if (DENY.test(a.license)) bad.push(`${a.name} (${a.license})`);
  out.push(`${a.name} (${a.license})`, '-'.repeat(60), a.note, '');
  out.push(existsSync(a.text) ? readFileSync(a.text, 'utf8').trim() : `(licence text: ${a.text})`, '', '');
}

if (bad.length) {
  console.error(`licenses: copyleft dependencies in the bundle: ${bad.join(', ')}`);
  process.exit(1);
}
writeFileSync(join(dist, 'third-party-licenses.txt'), out.join('\n'));
console.log(`licenses: ${seen.size} packages written to ${dist}/third-party-licenses.txt`);
