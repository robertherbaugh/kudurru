// Package dnsdist renders dnsdist configuration from an edge.Topology and
// supervises the dnsdist process (`kudurru edge run`, docs/architecture.md
// §3.6 and D16/D17). The YAML renderer (dnsdist 2.1 `dnsdist.yml` plus a
// sibling `dnsdist.lua` holding functions only) is primary; the Lua
// renderer (`dnsdist.conf`) is the fallback for the console diff-apply
// path should the v0.2 spike find YAML unworkable. Both consume the same
// Topology. enableLuaConfiguration() is never rendered.
package dnsdist

import (
	"fmt"
	"strings"

	"github.com/google/uuid"

	"github.com/robertherbaugh/kudurru/internal/edge"
)

// File is one rendered file, named relative to the configuration
// directory.
type File struct {
	Name string
	Data []byte
}

// Renderer turns a Topology into dnsdist configuration files. Main() is
// the file passed to `dnsdist -C`; the others are its siblings.
type Renderer interface {
	Name() string
	Main() string
	Render(t *edge.Topology) ([]File, error)
}

// NewRenderer returns the renderer called name ("yaml" or "lua").
func NewRenderer(name string) (Renderer, error) {
	switch strings.ToLower(name) {
	case "", "yaml", "yml":
		return YAMLRenderer{}, nil
	case "lua":
		return LuaRenderer{}, nil
	}
	return nil, fmt.Errorf("dnsdist: unknown renderer %q (want yaml or lua)", name)
}

// header starts every rendered file.
const header = "Generated by `kudurru edge run` (docs/architecture.md §3.6). Do not edit: the supervisor rewrites this file on every membership or certificate change."

// Rule names, stable so that the API's rules[] and the console address
// them across restarts.
const (
	ruleRefuseTransfers = "kudurru-refuse-xfr-notify-update"
	ruleProxySecret     = "kudurru-proxy-protocol-secret" //nolint:gosec // a rule name, not a credential
	ruleAuthoritative   = "kudurru-authoritative-zones"
	ruleResolver        = "kudurru-resolver-default"
)

// ruleUUID is the deterministic uuid of a rendered rule.
func ruleUUID(name string) string {
	return uuid.NewSHA1(edge.BackendNamespace, []byte("rule:"+name)).String()
}

// validatorName is the Lua function validating the health-check answer of
// backend b; empty when the backend has no node name to check.
func validatorName(t *edge.Topology, b edge.Backend) string {
	if !t.HealthCheck.ValidateNodeID || b.Name == "" {
		return ""
	}
	return "kudurru_validate_" + strings.ReplaceAll(b.ID, "-", "")
}

// prepare normalizes a copy of t and validates it.
func prepare(t *edge.Topology) (*edge.Topology, error) {
	c := *t
	c.Backends = append([]edge.Backend(nil), t.Backends...)
	c.Binds = append([]edge.Bind(nil), t.Binds...)
	c.Pools = make([]edge.Pool, len(t.Pools))
	for i, p := range t.Pools {
		c.Pools[i] = p
		if p.Cache != nil {
			pc := *p.Cache
			c.Pools[i].Cache = &pc
		}
	}
	c.Normalize()
	if err := c.Validate(); err != nil {
		return nil, fmt.Errorf("dnsdist: invalid topology: %w", err)
	}
	return &c, nil
}

// luaHealthHelpers are the shared Lua helpers of the validation functions.
// A kudurru health answer is TXT "<node-id> <serial-epoch>"; the helper
// returns the first TXT character-string of the answer section.
const luaHealthHelpers = `local function kudurru_health_txt(dr)
  if dr.dh:getRCODE() ~= DNSRCode.NOERROR then
    return nil
  end
  local packet = dr:getContent()
  local overlay = newDNSPacketOverlay(packet)
  for i = 0, overlay:getRecordsCountInSection(DNSSection.Answer) - 1 do
    local rec = overlay:getRecord(i)
    if rec.type == DNSQType.TXT and rec.contentLength > 1 then
      local len = string.byte(packet, rec.contentOffset + 1)
      return string.sub(packet, rec.contentOffset + 2, rec.contentOffset + 1 + len)
    end
  end
  return nil
end

local function kudurru_node_is(dr, node)
  local txt = kudurru_health_txt(dr)
  return txt ~= nil and (txt == node or string.sub(txt, 1, #node + 1) == node .. " ")
end
`

// luaValidators renders the helpers and one global validation function per
// named backend; empty when no backend is validated.
func luaValidators(t *edge.Topology) string {
	var b strings.Builder
	for _, be := range t.Backends {
		name := validatorName(t, be)
		if name == "" {
			continue
		}
		if b.Len() == 0 {
			b.WriteString(luaHealthHelpers)
		}
		fmt.Fprintf(&b, "\n-- backend %s (%s)\nfunction %s(dr)\n  return kudurru_node_is(dr, %s)\nend\n", be.Name, be.Address, name, luaString(be.Name))
	}
	return b.String()
}

// luaString quotes s for Lua. Topology.Validate restricts every rendered
// string to printable ASCII, for which Go and Lua quoting agree.
func luaString(s string) string {
	return fmt.Sprintf("%q", s)
}

func luaStrings(in []string) string {
	q := make([]string, len(in))
	for i, s := range in {
		q[i] = luaString(s)
	}
	return "{" + strings.Join(q, ", ") + "}"
}
