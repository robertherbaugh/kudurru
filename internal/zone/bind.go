package zone

import (
	"bufio"
	"fmt"
	"io"
	"strings"

	"github.com/miekg/dns"
	metav1 "k8s.io/apimachinery/pkg/apis/meta/v1"

	"github.com/robertherbaugh/kudurru/api/v1alpha1"
)

// Imported is a BIND zone file translated into the kudurru object model:
// the SOA and apex NS become DNSZoneSpec fields, everything else becomes
// Endpoints grouped by owner name and type in file order.
type Imported struct {
	// Spec has ZoneName, Type primary, SOA, Nameservers and DefaultTTL
	// (the SOA record's TTL) filled in.
	Spec v1alpha1.DNSZoneSpec
	// Serial is the SOA serial found in the file; the controller stamps
	// max(Serial+1, unix_now) so secondaries keep moving forward.
	Serial    uint32
	Endpoints []v1alpha1.Endpoint
	// Warnings lists records that were skipped (DNSSEC data, which the
	// v1.0 signer regenerates) and other lossy conversions.
	Warnings []string
}

// MaxEndpointsPerRecordSet is the CRD ceiling on spec.endpoints.
const MaxEndpointsPerRecordSet = 1000

// MaxImportRecords bounds the records ImportBIND accepts from one file.
// $GENERATE lines expand to up to 65,536 records each, so a short file can
// otherwise ask for an unbounded amount of memory.
const MaxImportRecords = 1_000_000

// importLimit is MaxImportRecords; tests lower it.
var importLimit = MaxImportRecords

// dnssecType reports types an import skips because the signer owns them.
func dnssecType(t uint16) bool {
	switch t {
	case dns.TypeRRSIG, dns.TypeNSEC, dns.TypeNSEC3, dns.TypeNSEC3PARAM,
		dns.TypeDNSKEY, dns.TypeCDS, dns.TypeCDNSKEY:
		return true
	}
	return false
}

// ImportBIND parses an RFC 1035 master file for the zone origin. $INCLUDE
// is refused; $ORIGIN, $TTL and $GENERATE work as in miekg's zone parser.
// Names in the result are absolute. Types without a mnemonic in
// SupportedTypes are converted to TYPEnnn with RFC 3597 rdata so nothing
// but DNSSEC data is lost.
func ImportBIND(r io.Reader, origin string) (*Imported, error) {
	origin = fqdn(origin)
	okey, err := canonicalKey(origin)
	if err != nil {
		return nil, fmt.Errorf("zone: import: origin %q: %w", origin, err)
	}
	im := &Imported{Spec: v1alpha1.DNSZoneSpec{ZoneName: origin, Type: v1alpha1.ZoneTypePrimary}}
	type groupKey struct {
		owner string
		t     uint16
	}
	index := map[groupKey]int{}
	var ttls []uint32
	var nsTTL uint32
	sawSOA := false

	zp := dns.NewZoneParser(r, origin, "")
	zp.SetDefaultTTL(DefaultTTL)
	records := 0
	for rr, ok := zp.Next(); ok; rr, ok = zp.Next() {
		if records++; records > importLimit {
			return nil, fmt.Errorf("zone: import: more than %d records", importLimit)
		}
		h := rr.Header()
		owner := fqdn(h.Name)
		if h.Class != dns.ClassINET {
			return nil, fmt.Errorf("zone: import: %s: class %s is not supported", owner, dns.ClassToString[h.Class])
		}
		key, err := canonicalKey(owner)
		if err != nil || !isKeyPrefix(key, okey) {
			return nil, fmt.Errorf("zone: import: %s is outside zone %s", owner, origin)
		}
		apex := key == okey
		switch {
		case h.Rrtype == dns.TypeSOA:
			if !apex {
				return nil, fmt.Errorf("zone: import: SOA at %s, not at the apex", owner)
			}
			if sawSOA {
				return nil, fmt.Errorf("zone: import: more than one SOA")
			}
			sawSOA = true
			soa := rr.(*dns.SOA)
			im.Serial = soa.Serial
			im.Spec.DefaultTTL = h.Ttl
			im.Spec.SOA = &v1alpha1.SOASpec{
				MName: soa.Ns, RName: soa.Mbox,
				Refresh: soa.Refresh, Retry: soa.Retry, Expire: soa.Expire, Minimum: soa.Minttl,
			}
			continue
		case h.Rrtype == dns.TypeNS && apex:
			im.Spec.Nameservers = append(im.Spec.Nameservers, fqdn(rr.(*dns.NS).Ns))
			nsTTL = h.Ttl
			continue
		case dnssecType(h.Rrtype):
			im.Warnings = append(im.Warnings, fmt.Sprintf("skipped %s %s: DNSSEC records are generated by the signer", owner, typeString(h.Rrtype)))
			continue
		case forbiddenType(h.Rrtype):
			return nil, fmt.Errorf("zone: import: %s %s cannot be served from records", owner, typeString(h.Rrtype))
		}
		rtype, target := endpointRdata(rr)
		gk := groupKey{key, h.Rrtype}
		i, ok := index[gk]
		if !ok {
			i = len(im.Endpoints)
			index[gk] = i
			im.Endpoints = append(im.Endpoints, v1alpha1.Endpoint{DNSName: endpointName(owner), RecordType: rtype})
			ttls = append(ttls, h.Ttl)
		}
		ep := &im.Endpoints[i]
		ep.Targets = append(ep.Targets, target)
		if h.Ttl != ttls[i] {
			if h.Ttl < ttls[i] {
				ttls[i] = h.Ttl
			}
			im.Warnings = append(im.Warnings, fmt.Sprintf("%s %s: records with different TTLs; using the smallest (RFC 2181 §5.2)", owner, rtype))
		}
	}
	if err := zp.Err(); err != nil {
		return nil, fmt.Errorf("zone: import: %w", err)
	}
	if !sawSOA {
		im.Warnings = append(im.Warnings, "no SOA record; defaults apply")
	}
	if im.Spec.DefaultTTL == 0 {
		im.Spec.DefaultTTL = DefaultTTL
	}
	if nsTTL != 0 && nsTTL != im.Spec.DefaultTTL {
		im.Warnings = append(im.Warnings, fmt.Sprintf("apex NS TTL %d replaced by the zone default TTL %d", nsTTL, im.Spec.DefaultTTL))
	}
	for i := range im.Endpoints {
		if ttls[i] != im.Spec.DefaultTTL {
			im.Endpoints[i].RecordTTL = int64(ttls[i])
		}
	}
	return im, nil
}

// endpointName renders an absolute owner name in the external-dns style
// (no trailing dot); "@" for the apex of the root zone.
func endpointName(owner string) string {
	if owner == "." {
		return "@"
	}
	return strings.TrimSuffix(owner, ".")
}

// endpointRdata returns the Endpoint recordType and target text of rr.
func endpointRdata(rr dns.RR) (string, string) {
	t := rr.Header().Rrtype
	if _, ok := supportedTypes[typeString(t)]; ok {
		if _, unknown := rr.(*dns.RFC3597); !unknown {
			return typeString(t), rdataText(rr)
		}
	}
	u := new(dns.RFC3597)
	if err := u.ToRFC3597(rr); err != nil {
		return typeString(t), rdataText(rr)
	}
	return "TYPE" + fmt.Sprint(t), rdataText(u)
}

// rdataText is the presentation rdata of rr: its String() without the
// header. miekg prints the four header fields (owner, TTL, class, type)
// tab-separated, and an owner name never holds a raw tab (it is escaped as
// \009), so the rdata is everything after the fourth tab. Splitting this
// way also covers RFC 3597 records, whose header prints as CLASSnnn.
func rdataText(rr dns.RR) string {
	parts := strings.SplitN(rr.String(), "\t", 5)
	if len(parts) < 5 {
		return ""
	}
	return parts[4]
}

// Objects splits the import into a DNSZone named zoneObject and as many
// DNSRecordSets in namespace as the 1000-endpoint ceiling needs, named
// <recordSetPrefix>, <recordSetPrefix>-2, ...
func (im *Imported) Objects(zoneObject, namespace, recordSetPrefix string) (*v1alpha1.DNSZone, []*v1alpha1.DNSRecordSet) {
	dz := &v1alpha1.DNSZone{
		TypeMeta:   metav1.TypeMeta{APIVersion: v1alpha1.GroupVersion.String(), Kind: "DNSZone"},
		ObjectMeta: metav1.ObjectMeta{Name: zoneObject},
		Spec:       im.Spec,
	}
	var out []*v1alpha1.DNSRecordSet
	for i := 0; i < len(im.Endpoints); i += MaxEndpointsPerRecordSet {
		end := min(i+MaxEndpointsPerRecordSet, len(im.Endpoints))
		name := recordSetPrefix
		if i > 0 {
			name = fmt.Sprintf("%s-%d", recordSetPrefix, i/MaxEndpointsPerRecordSet+1)
		}
		out = append(out, &v1alpha1.DNSRecordSet{
			TypeMeta:   metav1.TypeMeta{APIVersion: v1alpha1.GroupVersion.String(), Kind: "DNSRecordSet"},
			ObjectMeta: metav1.ObjectMeta{Name: name, Namespace: namespace},
			Spec: v1alpha1.DNSRecordSetSpec{
				ZoneRef:   v1alpha1.ObjectRef{Name: zoneObject},
				Endpoints: append([]v1alpha1.Endpoint(nil), im.Endpoints[i:end]...),
			},
		})
	}
	return dz, out
}

// ExportBIND writes z as an RFC 1035 master file: $ORIGIN, $TTL, the SOA,
// then every RRset in canonical order with absolute names, one record per
// line. ImportBIND of the output rebuilds a zone with the same content
// hash, and exporting that zone again gives identical bytes.
func ExportBIND(w io.Writer, z *Zone) error {
	if z.soa == nil {
		return fmt.Errorf("zone: export: %s is a %s zone and has no records", z.name, z.typ)
	}
	// bufio.Writer latches the first write error and Flush reports it, so
	// the individual writes need no checks.
	bw := bufio.NewWriter(w)
	_, _ = fmt.Fprintf(bw, "; zone %s serial %d exported by kudurru\n", z.name, z.serial)
	_, _ = fmt.Fprintf(bw, "$ORIGIN %s\n$TTL %d\n", z.name, z.soa.Hdr.Ttl)
	z.RRsets(func(s *RRset) bool {
		for _, rr := range s.RRs {
			_, _ = bw.WriteString(rr.String())
			_ = bw.WriteByte('\n')
		}
		return true
	})
	return bw.Flush()
}
