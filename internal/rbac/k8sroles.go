package rbac

import (
	"bytes"
	"fmt"
	"slices"
	"sort"
	"strings"
)

// AggregatedRolesPath is where `make rbac-manifests` writes the chart's
// aggregated ClusterRoles, relative to the repository root.
const AggregatedRolesPath = "charts/kudurru/templates/rbac-aggregated.yaml"

// PolicyRule is a Kubernetes RBAC rule (rbac.authorization.k8s.io/v1),
// reduced to the fields the generated ClusterRoles use.
type PolicyRule struct {
	APIGroups []string
	Resources []string
	Verbs     []string
}

// kubernetesVerbs maps a kudurru verb to the Kubernetes verbs a
// ClusterRole grants for it. SARVerb asks get/list for read and
// update/create for write; watch and patch are added so kubectl and
// server-side apply work on the CRD-backed resources. The other verbs
// (toggle, flush, refresh, export, purge, transfer, own, ...) are custom
// verbs that SubjectAccessReview passes through unchanged.
func kubernetesVerbs(verb string) []string {
	switch verb {
	case "read":
		return []string{"get", "list", "watch"}
	case "write":
		return []string{"create", "update", "patch"}
	}
	return []string{verb}
}

// KubernetesRules returns the ClusterRole rules of a role: every
// permission becomes the SARResources name with the kubernetesVerbs of its
// verb, and resources with the same verb set share one rule. "*.*" is the
// kudurru.io wildcard.
func (p *Permissions) KubernetesRules(role string) []PolicyRule {
	verbs := map[string]map[string]bool{} // SAR resource -> Kubernetes verbs
	add := func(res, verb string) {
		name, ok := SARResources[res]
		if !ok {
			return
		}
		if verbs[name] == nil {
			verbs[name] = map[string]bool{}
		}
		for _, v := range kubernetesVerbs(verb) {
			verbs[name][v] = true
		}
	}
	for _, perm := range p.Roles[role] {
		res, verb, _ := strings.Cut(perm, ".")
		if res == "*" && verb == "*" {
			return []PolicyRule{{APIGroups: []string{SARGroup}, Resources: []string{"*"}, Verbs: []string{"*"}}}
		}
		resources := []string{res}
		if res == "*" {
			resources = resources[:0]
			for r := range p.Resources {
				resources = append(resources, r)
			}
		}
		for _, r := range resources {
			if verb == "*" {
				for _, v := range p.Resources[r] {
					add(r, v)
				}
			} else if slices.Contains(p.Resources[r], verb) {
				add(r, verb)
			}
		}
	}
	// Group resources by verb set; order rules by verb set, resources by name.
	byVerbs := map[string][]string{}
	for name, vs := range verbs {
		list := make([]string, 0, len(vs))
		for v := range vs {
			list = append(list, v)
		}
		sort.Slice(list, func(i, j int) bool { return verbRank(list[i], list[j]) })
		key := strings.Join(list, ",")
		byVerbs[key] = append(byVerbs[key], name)
	}
	keys := make([]string, 0, len(byVerbs))
	for k := range byVerbs {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	out := make([]PolicyRule, 0, len(keys))
	for _, k := range keys {
		res := byVerbs[k]
		sort.Strings(res)
		out = append(out, PolicyRule{APIGroups: []string{SARGroup}, Resources: res, Verbs: strings.Split(k, ",")})
	}
	return out
}

// verbRank orders the standard verbs the way RBAC manifests usually list
// them and the custom verbs alphabetically after them.
func verbRank(a, b string) bool {
	std := []string{"get", "list", "watch", "create", "update", "patch", "delete"}
	ia, ib := slices.Index(std, a), slices.Index(std, b)
	switch {
	case ia >= 0 && ib >= 0:
		return ia < ib
	case ia >= 0:
		return true
	case ib >= 0:
		return false
	}
	return a < b
}

// RenderAggregatedRoles returns the Helm template of the user-facing
// ClusterRoles (D31, §5.3): one per role in the kubernetes section of
// permissions.yaml, labelled for aggregation into the built-in role it
// names. `make rbac-manifests` writes it to AggregatedRolesPath and a test
// fails when the committed file drifts.
func (p *Permissions) RenderAggregatedRoles() []byte {
	var b bytes.Buffer
	w := func(format string, args ...any) { fmt.Fprintf(&b, format+"\n", args...) }
	w("{{- /*")
	w("GENERATED by `make rbac-manifests` from internal/rbac/permissions.yaml (D31).")
	w("Do not edit: change permissions.yaml and regenerate; TestAggregatedRolesDrift")
	w("fails when this file is stale.")
	w("*/ -}}")
	w(`{{- if and .Values.rbac.create .Values.rbac.aggregateToDefaultRoles (not (include "kudurru.standalone" .)) }}`)
	w("# User-facing roles: real CRDs plus the virtual resources kudurru checks")
	w("# with SubjectAccessReview (§5.5). Custom verbs (flush, toggle, refresh,")
	w("# export, ...) are what SubjectAccessReview asks for those operations.")
	roles := make([]string, 0, len(p.Kubernetes))
	for r := range p.Kubernetes {
		roles = append(roles, r)
	}
	// Least to most privileged as the role list in permissions.yaml has
	// no order of its own: by the number of granted rules, then by name.
	sort.Slice(roles, func(i, j int) bool {
		ri, rj := roleWeight(p, roles[i]), roleWeight(p, roles[j])
		if ri != rj {
			return ri < rj
		}
		return roles[i] < roles[j]
	})
	for i, role := range roles {
		k := p.Kubernetes[role]
		if i > 0 {
			w("---")
		}
		w("# kudurru role %q.", role)
		w("apiVersion: rbac.authorization.k8s.io/v1")
		w("kind: ClusterRole")
		w("metadata:")
		w(`  name: {{ include "kudurru.fullname" . }}-%s`, k.ClusterRole)
		w("  labels:")
		w(`    {{- include "kudurru.labels" . | nindent 4 }}`)
		if k.AggregateTo != "" {
			w(`    rbac.authorization.k8s.io/aggregate-to-%s: "true"`, k.AggregateTo)
		}
		w("rules:")
		for _, r := range p.KubernetesRules(role) {
			w("  - apiGroups: [%s]", quoteList(r.APIGroups))
			w("    resources: [%s]", quoteList(r.Resources))
			w("    verbs: [%s]", quoteList(r.Verbs))
		}
	}
	w("{{- end }}")
	return b.Bytes()
}

// roleWeight orders roles for rendering: "*.*" last, otherwise by the
// number of permissions.
func roleWeight(p *Permissions, role string) int {
	if slices.Contains(p.Roles[role], "*.*") {
		return 1 << 30
	}
	return len(p.Roles[role])
}

func quoteList(in []string) string {
	q := make([]string, len(in))
	for i, s := range in {
		q[i] = `"` + s + `"`
	}
	return strings.Join(q, ", ")
}
