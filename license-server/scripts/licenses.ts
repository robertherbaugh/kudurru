// Writes dist/ui/third-party-licenses.txt: name, version, license and the
// license text of every production dependency the image distributes,
// walked from package.json "dependencies" transitively. That covers both
// bundles: the UI (React, Astryx, TanStack Query, lucide) and the server
// (openid-client with oauth4webapi and jose, nodemailer). The Dockerfile
// copies the file to /app/third-party-licenses.txt next to /app/NOTICE,
// which covers the Bun runtime and the base image. Fails on a copyleft
// license (CONTRIBUTING.md), as web/scripts/licenses.ts does.
//
//   bun scripts/licenses.ts [dist/ui]
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const dist = process.argv[2] ?? join('dist', 'ui');
const DENY = /\b(A?GPL|LGPL|EUPL|SSPL|MPL)\b/i;

interface Pkg {
  name: string;
  version: string;
  license?: string;
  author?: string | { name?: string };
  homepage?: string;
  dependencies?: Record<string, string>;
}

const seen = new Map<string, { pkg: Pkg; dir: string }>();

function visit(name: string): void {
  if (seen.has(name)) return;
  const dir = join('node_modules', name);
  const file = join(dir, 'package.json');
  if (!existsSync(file)) return; // an optional or peer dependency that is not installed
  const pkg = JSON.parse(readFileSync(file, 'utf8')) as Pkg;
  seen.set(name, { pkg, dir });
  for (const dep of Object.keys(pkg.dependencies ?? {})) visit(dep);
}

const root = JSON.parse(readFileSync('package.json', 'utf8')) as Pkg;
for (const dep of Object.keys(root.dependencies ?? {})) visit(dep);

function textOf(dir: string, pattern: RegExp): string {
  const f = readdirSync(dir).find((n) => pattern.test(n));
  return f ? readFileSync(join(dir, f), 'utf8').trim() : '';
}

