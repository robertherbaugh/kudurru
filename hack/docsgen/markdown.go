package main

import (
	"encoding/json"
	"fmt"
	"sort"
	"strconv"
	"strings"
)

// generatedNote heads every page: an HTML comment, invisible on the site
// and on GitHub.
func generatedNote(source string) string {
	return fmt.Sprintf("<!-- Generated by hack/docsgen from %s; do not edit. Run `make docs-gen`. -->\n\n", source)
}

// frontMatter renders the YAML front matter Hugo needs for a generated page.
func frontMatter(title, description string, weight int) string {
	var b strings.Builder
	b.WriteString("---\n")
	fmt.Fprintf(&b, "title: %s\n", strconv.Quote(title))
	if description != "" {
		fmt.Fprintf(&b, "description: %s\n", strconv.Quote(description))
	}
	if weight != 0 {
		fmt.Fprintf(&b, "weight: %d\n", weight)
	}
	b.WriteString("---\n\n")
	return b.String()
}

// text escapes prose for a markdown table cell. Code spans (`...`) are
// kept; outside them the characters that would start emphasis, a link or
// raw HTML are escaped. Line breaks become spaces, and pipes are escaped
// everywhere because GFM splits cells on them even inside code spans.
func text(s string) string {
	s = strings.Join(strings.Fields(s), " ")
	var b strings.Builder
	inCode := false
	for _, r := range s {
		switch {
		case r == '`':
			inCode = !inCode
			b.WriteRune(r)
		case r == '|':
			b.WriteString(`\|`)
		case inCode:
			b.WriteRune(r)
		case r == '<':
			b.WriteString("&lt;")
		case r == '>':
			b.WriteString("&gt;")
		case strings.ContainsRune(`\*_[]`, r):
			b.WriteByte('\\')
			b.WriteRune(r)
		default:
			b.WriteRune(r)
		}
	}
	return b.String()
}

// code renders s as a code span that is safe inside a table cell.
func code(s string) string {
	if s == "" {
		return ""
	}
	s = strings.ReplaceAll(s, "|", `\|`)
	if strings.Contains(s, "`") {
		return "`` " + s + " ``"
	}
	return "`" + s + "`"
}

// flow renders a default value in YAML flow style ({a: 1, b: [x, y]}): short,
// valid YAML, and it wraps at the spaces in a narrow table column.
func flow(v any) string {
	b, err := json.Marshal(v)
	if err != nil {
		return fmt.Sprint(v)
	}
	var generic any
	if err := json.Unmarshal(b, &generic); err != nil {
		return string(b)
	}
	return flowValue(generic)
}

func flowValue(v any) string {
	switch t := v.(type) {
	case nil:
		return "null"
	case string:
		if t == "" || strings.ContainsAny(t, ",:{}[]#&*!|>'\"%@`") || strings.TrimSpace(t) != t {
			return strconv.Quote(t)
		}
		return t
	case float64:
		return strconv.FormatFloat(t, 'f', -1, 64)
	case bool:
		return strconv.FormatBool(t)
	case []any:
		parts := make([]string, len(t))
		for i, e := range t {
			parts[i] = flowValue(e)
		}
		return "[" + strings.Join(parts, ", ") + "]"
	case map[string]any:
		keys := make([]string, 0, len(t))
		for k := range t {
			keys = append(keys, k)
		}
		sort.Strings(keys)
		parts := make([]string, len(keys))
		for i, k := range keys {
			parts[i] = flowValue(k) + ": " + flowValue(t[k])
		}
		return "{" + strings.Join(parts, ", ") + "}"
	default:
		return fmt.Sprint(t)
	}
}
