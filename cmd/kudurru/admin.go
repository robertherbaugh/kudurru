package main

import (
	"encoding/json"
	"errors"
	"fmt"
	"strconv"
	"strings"

	"github.com/spf13/cobra"

	"github.com/robertherbaugh/kudurru/internal/cli"
)

// Admin socket operations. The protocol is newline-delimited JSON over the
// unix socket: {op, args} → {ok, result, error} (see internal/cli.AdminCall
// and docs/m3/cli.md).
const (
	adminOpResetPassword = "reset-password"
	adminOpCreateToken   = "create-token"
	adminOpListUsers     = "list-users"
)

// newAdminCmd is `kudurru admin`: break-glass operations over the local
// unix socket, for `docker exec` / `kubectl exec` when nobody can log in.
func newAdminCmd(o *cliOpts) *cobra.Command {
	var socket string
	cmd := &cobra.Command{
		Use:   "admin",
		Short: "Break-glass account recovery over the local unix socket",
		Long: `Break-glass operations over the server's unix socket (default
/run/kudurru/kudurru.sock). They do not use the API or a token: the server
admits root, its own user (65532 in the distroless image, which is what
docker exec and kubectl exec get), or a configured group.

  docker exec kudurru kudurru admin reset-password admin
  kubectl exec -n dns deploy/kudurru -- kudurru admin create-token --name ci`,
	}
	cmd.PersistentFlags().StringVar(&socket, "socket", "", "admin socket path (default $KUDURRU_ADMIN_SOCKET or "+cli.DefaultAdminSocket+")")
	sock := func() string { return firstNonEmpty(socket, o.getenv("KUDURRU_ADMIN_SOCKET"), cli.DefaultAdminSocket) }

	var (
		password      string
		passwordStdin bool
	)
	reset := &cobra.Command{
		Use:   "reset-password <username>",
		Short: "Set a local user's password (generated when none is given) and require a change at next login",
		Args:  cobra.ExactArgs(1),
		RunE: func(cmd *cobra.Command, args []string) error {
			pw := password
			if passwordStdin {
				var err error
				if pw, err = o.readPassword(cmd, "", true, args[0]); err != nil {
					return err
				}
			}
			req := map[string]any{"username": args[0]}
			if pw != "" {
				req["password"] = pw
			}
			var res struct {
				Username           string `json:"username"`
				Password           string `json:"password"`
				MustChangePassword *bool  `json:"mustChangePassword"`
			}
			if err := cli.AdminCall(cmd.Context(), sock(), adminOpResetPassword, req, &res); err != nil {
				return err
			}
			w := cmd.OutOrStdout()
			_, _ = fmt.Fprintf(w, "Password of %s reset.\n", firstNonEmpty(res.Username, args[0]))
			if res.Password != "" && pw == "" {
				_, _ = fmt.Fprintf(w, "New password (shown once): %s\n", res.Password)
			}
			if res.MustChangePassword == nil || *res.MustChangePassword {
				_, _ = fmt.Fprintln(w, "The user must change it at the next login.")
			}
			return nil
		},
	}
	reset.Flags().StringVar(&password, "password", "", "new password (default: generated by the server)")
	reset.Flags().BoolVar(&passwordStdin, "password-stdin", false, "read the new password from stdin")

	var (
		name, user, sa, expires string
	)
	createToken := &cobra.Command{
		Use:   "create-token",
		Short: "Mint an API token for a user or service account and print it once",
		Args:  cobra.NoArgs,
		RunE: func(cmd *cobra.Command, _ []string) error {
			if user != "" && sa != "" {
				return errors.New("use --user or --service-account, not both")
			}
			req := map[string]any{"name": name}
			if user != "" {
				req["user"] = user
			}
			if sa != "" {
				req["serviceAccount"] = sa
			}
			if expires != "" {
				req["expiresIn"] = expires
			}
			var res struct {
				ID        string `json:"id"`
				Token     string `json:"token"`
				Secret    string `json:"secret"`
				ExpiresAt string `json:"expiresAt"`
				Owner     string `json:"owner"`
			}
			if err := cli.AdminCall(cmd.Context(), sock(), adminOpCreateToken, req, &res); err != nil {
				return err
			}
			tok := firstNonEmpty(res.Token, res.Secret)
			if tok == "" {
				return errors.New("admin create-token: the server returned no token")
			}
			f, _ := o.format()
			if f.Structured() {
				return cli.WriteStructured(cmd.OutOrStdout(), f, map[string]string{"id": res.ID, "token": tok, "expiresAt": res.ExpiresAt, "owner": res.Owner})
			}
			_, _ = fmt.Fprintln(cmd.OutOrStdout(), tok)
			msg := "token " + firstNonEmpty(res.ID, name) + " created (shown once)"
			if res.ExpiresAt != "" {
				msg += ", expires " + res.ExpiresAt
			}
			_, _ = fmt.Fprintln(cmd.ErrOrStderr(), msg)
			return nil
		},
	}
	createToken.Flags().StringVar(&name, "name", "admin-socket", "token name")
	createToken.Flags().StringVar(&user, "user", "", "owner user (default: the bootstrap admin)")
	createToken.Flags().StringVar(&sa, "service-account", "", "owner service account")
	createToken.Flags().StringVar(&expires, "expires-in", "", "lifetime, e.g. 720h (default: the server's)")

	listUsers := &cobra.Command{
		Use:   "list-users",
		Short: "List local users",
		Args:  cobra.NoArgs,
		RunE: func(cmd *cobra.Command, _ []string) error {
			var raw json.RawMessage
			if err := cli.AdminCall(cmd.Context(), sock(), adminOpListUsers, nil, &raw); err != nil {
				return err
			}
			items, err := rawItems(raw)
			if err != nil {
				var env struct {
					Users []json.RawMessage `json:"users"`
				}
				if json.Unmarshal(raw, &env) != nil {
					return err
				}
				items = env.Users
			}
			type user struct {
				Name               string   `json:"name"`
				Username           string   `json:"username"`
				Disabled           bool     `json:"disabled"`
				MustChangePassword bool     `json:"mustChangePassword"`
				Roles              []string `json:"roles"`
				Identities         []string `json:"identities"`
			}
			var users []user
			for _, it := range items {
				var u user
				if err := json.Unmarshal(it, &u); err != nil {
					return err
				}
				users = append(users, u)
			}
			return o.render(cmd, raw, func(bool) (*cli.Table, error) {
				t := &cli.Table{Headers: []string{"NAME", "DISABLED", "MUST-CHANGE-PASSWORD", "ROLES"}}
				for _, u := range users {
					t.Add(firstNonEmpty(u.Username, u.Name), strconv.FormatBool(u.Disabled), strconv.FormatBool(u.MustChangePassword), firstNonEmpty(strings.Join(u.Roles, ","), "-"))
				}
				return t, nil
			})
		},
	}
	cmd.AddCommand(reset, createToken, listUsers)
	return cmd
}
