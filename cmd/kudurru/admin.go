// adminUser is one entry of list-users.
type adminUser struct {
	Name               string     `json:"name"`
	Username           string     `json:"username,omitempty"`
	DisplayName        string     `json:"displayName,omitempty"`
	BuiltinAdmin       bool       `json:"builtinAdmin"`
	Disabled           bool       `json:"disabled"`
	MustChangePassword bool       `json:"mustChangePassword"`
	Groups             []string   `json:"groups,omitempty"`
	LastLoginAt        *time.Time `json:"lastLoginAt,omitempty"`
}

// tokenOwner renders the owner of a created token, an object
// {kind,name,namespace} or a plain string.
func tokenOwner(raw json.RawMessage) string {
	var s string
	if json.Unmarshal(raw, &s) == nil {
		return s
	}
	var o struct {
		Kind, Name, Namespace string
	}
	if json.Unmarshal(raw, &o) != nil || o.Name == "" {
		return ""
	}
	if o.Namespace != "" {
		return o.Kind + " " + o.Namespace + "/" + o.Name
	}
	return o.Kind + " " + o.Name
}

// newAdminCmd is `kudurru admin`: break-glass operations over the local
// unix socket, for `docker exec` / `kubectl exec` when nobody can log in.
func newAdminCmd(o *cliOpts) *cobra.Command {
	var socket, protocol string
	cmd := &cobra.Command{
		Use:   "admin",
		Short: "Break-glass account recovery over the local unix socket",
		Long: `Break-glass operations over the server's unix socket (default
/run/kudurru/kudurru.sock). They do not use the API or a token: the server
admits root, its own user (65532 in the distroless image, which is what
docker exec and kubectl exec get), or a configured group.

  docker exec kudurru kudurru admin reset-password admin
  kubectl exec -n dns deploy/kudurru -- kudurru admin create-token --expires-in 1h`,
	}
	cmd.PersistentFlags().StringVar(&socket, "socket", "", "admin socket path (default $KUDURRU_ADMIN_SOCKET or "+cli.DefaultAdminSocket+")")
	cmd.PersistentFlags().StringVar(&protocol, "protocol", cli.AdminProtocolAuto, "socket protocol: auto, http or ndjson")
	client := func() *cli.AdminClient {
		return &cli.AdminClient{Socket: firstNonEmpty(socket, o.getenv("KUDURRU_ADMIN_SOCKET"), cli.DefaultAdminSocket), Protocol: protocol}
	}

	var (
		password      string
		passwordStdin bool
		create        bool
	)
	reset := &cobra.Command{
		Use:   "reset-password [username]",
		Short: "Set a local user's password (generated when none is given) and require a change at next login",
		Long: `Set a local user's password and require a change at the next login. Without
--password the server generates one and prints it once. The username defaults
to the built-in admin; --create makes that account when it does not exist.`,
		Args: cobra.MaximumNArgs(1),
		RunE: func(cmd *cobra.Command, args []string) error {
			pw := password
			if passwordStdin {
				var err error
				if pw, err = o.readPassword(cmd, "", true, ""); err != nil {
					return err
				}
			}
			req := map[string]any{}
			if len(args) == 1 {
				req["username"] = args[0]
			}
			if pw != "" {
				req["password"] = pw
			}
			if create {
				req["create"] = true
			}
			var res struct {
				Username           string `json:"username"`
				Password           string `json:"password"`
				MustChangePassword *bool  `json:"mustChangePassword"`
				Created            bool   `json:"created"`
			}
			if err := client().Call(cmd.Context(), cli.AdminResetPassword, req, &res); err != nil {
				return err
			}
			w := cmd.OutOrStdout()
			user := firstNonEmpty(res.Username, firstArg(args), "admin")
			if res.Created {
				_, _ = fmt.Fprintf(w, "User %s created.\n", user)
			} else {
				_, _ = fmt.Fprintf(w, "Password of %s reset.\n", user)
			}
			if res.Password != "" && pw == "" {
				_, _ = fmt.Fprintf(w, "New password (shown once): %s\n", res.Password)
			}
			if res.MustChangePassword == nil || *res.MustChangePassword {
				_, _ = fmt.Fprintln(w, "The user must change it at the next login.")
			}
			return nil
		},
	}
	reset.Flags().StringVar(&password, "password", "", "new password (default: generated by the server)")
	reset.Flags().BoolVar(&passwordStdin, "password-stdin", false, "read the new password from stdin")
	reset.Flags().BoolVar(&create, "create", false, "create the user (as the built-in admin) when it does not exist")

	var user, description, expires string
	createToken := &cobra.Command{
		Use:   "create-token",
		Short: "Mint an API token and print it once (break-glass service account, or --user)",
		Long: `Mint an API token and print it once on stdout. Without --user the token
belongs to the built-in break-glass service account and expires after 24h
unless --expires-in says otherwise; with --user it is a personal token of that
local user.`,
		Args: cobra.NoArgs,
		RunE: func(cmd *cobra.Command, _ []string) error {
			req := map[string]any{}
			if user != "" {
				req["user"] = user
			}
			if description != "" {
				req["description"] = description
			}
			if expires != "" {
				if _, err := time.ParseDuration(expires); err != nil {
					return fmt.Errorf("--expires-in: %w", err)
				}
				req["expiresIn"] = expires
			}
			var res struct {
				ID        string          `json:"id"`
				Token     string          `json:"token"`
				Secret    string          `json:"secret"`
				ExpiresAt *time.Time      `json:"expiresAt"`
				Owner     json.RawMessage `json:"owner"`
			}
			if err := client().Call(cmd.Context(), cli.AdminCreateToken, req, &res); err != nil {
				return err
			}
			tok := firstNonEmpty(res.Token, res.Secret)
			if tok == "" {
				return errors.New("admin create-token: the server returned no token")
			}
			f, _ := o.format()
			if f.Structured() {
				return cli.WriteStructured(cmd.OutOrStdout(), f, map[string]any{"id": res.ID, "token": tok, "expiresAt": res.ExpiresAt, "owner": res.Owner})
			}
			_, _ = fmt.Fprintln(cmd.OutOrStdout(), tok)
			msg := "token " + firstNonEmpty(res.ID, "?") + " created (shown once)"
			if owner := tokenOwner(res.Owner); owner != "" {
				msg += " for " + owner
			}
			if res.ExpiresAt != nil {
				msg += ", expires " + res.ExpiresAt.UTC().Format(time.RFC3339)
			}
			_, _ = fmt.Fprintln(cmd.ErrOrStderr(), msg)
			return nil
		},
	}
	createToken.Flags().StringVar(&user, "user", "", "local user owning the token (default: the break-glass service account)")
	createToken.Flags().StringVar(&description, "description", "", "what the token is for")
	createToken.Flags().StringVar(&expires, "expires-in", "", "lifetime, e.g. 1h (default 24h for break-glass tokens)")

	listUsers := &cobra.Command{
		Use:   "list-users",
		Short: "List local users",
		Args:  cobra.NoArgs,
		RunE: func(cmd *cobra.Command, _ []string) error {
			var raw json.RawMessage
			if err := client().Call(cmd.Context(), cli.AdminListUsers, nil, &raw); err != nil {
				return err
			}
			var env struct {
				Users []adminUser `json:"users"`
			}
			if err := json.Unmarshal(raw, &env); err != nil {
				// A bare array or a list envelope.
				items, ierr := rawItems(raw)
				if ierr != nil {
					return err
				}
				for _, it := range items {
					var u adminUser
					if err := json.Unmarshal(it, &u); err != nil {
						return err
					}
					env.Users = append(env.Users, u)
				}
			}
			return o.render(cmd, raw, func(wide bool) (*cli.Table, error) {
				t := &cli.Table{Headers: []string{"NAME", "ADMIN", "DISABLED", "MUST-CHANGE-PASSWORD", "LAST-LOGIN"}}
				if wide {
					t.Headers = append(t.Headers, "DISPLAY-NAME", "GROUPS")
				}
				for _, u := range env.Users {
					last := "-"
					if u.LastLoginAt != nil {
						last = formatTime(*u.LastLoginAt)
					}
					row := []string{firstNonEmpty(u.Name, u.Username), strconv.FormatBool(u.BuiltinAdmin), strconv.FormatBool(u.Disabled), strconv.FormatBool(u.MustChangePassword), last}
					if wide {
						row = append(row, firstNonEmpty(u.DisplayName, "-"), firstNonEmpty(strings.Join(u.Groups, ","), "-"))
					}
					t.Add(row...)
				}
				return t, nil
			})
		},
	}
	cmd.AddCommand(reset, createToken, listUsers)
	return cmd
}

func firstArg(args []string) string {
	if len(args) > 0 {
		return args[0]
	}
	return ""
}
