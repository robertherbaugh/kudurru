var updateCLIReference = flag.Bool("update-cli-reference", false, "rewrite the CLI reference of the docs site (make docs-gen)")

// cliReferencePage is the docs site's CLI reference, generated from the
// command tree so it cannot drift from `kudurru --help`.
const cliReferencePage = "../../docs-site/content/reference/cli.md"

// TestCLIReferenceDrift fails when the committed CLI reference differs
// from the command tree; `make docs-gen` rewrites it.
func TestCLIReferenceDrift(t *testing.T) {
	t.Setenv("KUDURRU_CONFIG", "")
	got := cliReference(newRoot())
	if *updateCLIReference {
		if err := os.WriteFile(cliReferencePage, []byte(got), 0o644); err != nil { //nolint:gosec // documentation
			t.Fatal(err)
		}
		return
	}
	want, err := os.ReadFile(cliReferencePage)
	if err != nil {
		t.Fatalf("%v (run `make docs-gen`)", err)
	}
	if string(want) != got {
		t.Fatalf("%s is stale; run `make docs-gen` and commit the result", filepath.Clean(cliReferencePage))
	}
}

// cliReference renders every available command: the global flags once,
// then one section per top-level command and one per subcommand.
func cliReference(root *cobra.Command) string {
	var b strings.Builder
	b.WriteString("---\ntitle: \"CLI reference\"\ndescription: \"Every kudurru command, its arguments and its flags.\"\nweight: 30\n---\n\n")
	b.WriteString("<!-- Generated by TestCLIReferenceDrift (cmd/kudurru) from the command tree; do not edit. Run `make docs-gen`. -->\n\n")
	b.WriteString("One binary is the server, the supervisors and the client. The client verbs\n" +
		"talk to the REST API of a server chosen by `--server` or a context saved by\n" +
		"`kudurru login`; `kudurru admin` talks to the local admin socket instead. The\n" +
		"same text is available offline as `kudurru <command> --help`.\n\n")
	b.WriteString("## Global flags\n\nEvery command accepts these flags.\n\n")
	fmt.Fprintf(&b, "```text\n%s```\n", root.PersistentFlags().FlagUsagesWrapped(100))
	for _, c := range root.Commands() {
		if !c.IsAvailableCommand() || c.Name() == "help" {
			continue
		}
		writeCommand(&b, c, 2)
	}
	return regexp.MustCompile(`\n{3,}`).ReplaceAllString(b.String(), "\n\n")
}

func writeCommand(b *strings.Builder, c *cobra.Command, level int) {
	if level > 4 {
		level = 4
	}
	fmt.Fprintf(b, "\n%s %s\n\n", strings.Repeat("#", level), c.CommandPath())
	if c.Long != "" {
		b.WriteString(longText(c.Long))
	} else if c.Short != "" {
		b.WriteString(mdEscape(c.Short) + ".\n\n")
	}
	if c.Runnable() {
		fmt.Fprintf(b, "```text\n%s\n```\n\n", c.UseLine())
	}
	if len(c.Aliases) > 0 {
		fmt.Fprintf(b, "Aliases: `%s`.\n\n", strings.Join(c.Aliases, "`, `"))
	}
	if c.Example != "" {
		fmt.Fprintf(b, "Examples:\n\n```sh\n%s\n```\n\n", dedent(c.Example))
	}
	if fs := c.NonInheritedFlags(); fs.HasAvailableFlags() {
		fmt.Fprintf(b, "Flags:\n\n```text\n%s```\n\n", fs.FlagUsagesWrapped(100))
	}
	for _, sub := range c.Commands() {
		if sub.IsAvailableCommand() {
			writeCommand(b, sub, level+1)
		}
	}
}

// longText renders a command's Long help: paragraphs become markdown
// paragraphs, and paragraphs indented by two spaces or more (examples)
// become text blocks.
func longText(s string) string {
	var b strings.Builder
	for _, para := range strings.Split(strings.TrimSpace(s), "\n\n") {
		lines := strings.Split(strings.Trim(para, "\n"), "\n")
		indented := true
		for _, l := range lines {
			if !strings.HasPrefix(l, "  ") {
				indented = false
			}
		}
		if indented {
			for i, l := range lines {
				lines[i] = strings.TrimPrefix(l, "  ")
			}
			fmt.Fprintf(&b, "```text\n%s\n```\n\n", strings.Join(lines, "\n"))
			continue
		}
		b.WriteString(mdEscape(strings.Join(strings.Fields(para), " ")) + "\n\n")
	}
	return b.String()
}

// mdEscape escapes the characters of plain help text that markdown would
// read as markup (emphasis, links, raw HTML such as <zone>); code spans
// are kept as they are.
func mdEscape(s string) string {
	var b strings.Builder
	inCode := false
	for _, r := range s {
		switch {
		case r == '`':
			inCode = !inCode
			b.WriteRune(r)
		case inCode:
			b.WriteRune(r)
		case r == '<':
			b.WriteString("&lt;")
		case r == '>':
			b.WriteString("&gt;")
		case strings.ContainsRune(`\*_[]`, r):
			b.WriteByte('\\')
			b.WriteRune(r)
		default:
			b.WriteRune(r)
		}
	}
	return b.String()
}

// dedent removes the indentation common to every non-blank line (cobra
// examples are indented for the terminal).
func dedent(s string) string {
	lines := strings.Split(strings.Trim(s, "\n"), "\n")
	indent := -1
	for _, l := range lines {
		if strings.TrimSpace(l) == "" {
			continue
		}
		if n := len(l) - len(strings.TrimLeft(l, " ")); indent < 0 || n < indent {
			indent = n
		}
	}
	for i, l := range lines {
		if indent > 0 && len(l) >= indent {
			lines[i] = l[indent:]
		}
	}
	return strings.Join(lines, "\n")
}
